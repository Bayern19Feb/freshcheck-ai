// Builds an Android app package (.apk for installing, .aab for Google Play) for the
// deployed PWA using PWABuilder's free packaging service — the same request the
// pwabuilder.com website sends. Output goes to android-package/ (git-ignored,
// because it contains the private signing key).
// Run: node tools/android/make-apk.mjs

import { mkdirSync, writeFileSync } from 'node:fs';

const SERVICE = 'https://pwabuilder-cloudapk.azurewebsites.net';
const SITE = 'https://bayern19feb.github.io/freshcheck-ai/';
const OUT = 'android-package';

const options = {
  appVersion: '1.0.0',
  appVersionCode: 1,
  backgroundColor: '#f5f6f1',
  display: 'standalone',
  enableNotifications: false,
  enableSiteSettingsShortcut: true,
  fallbackType: 'customtabs',
  features: { locationDelegation: { enabled: false }, playBilling: { enabled: false } },
  host: new URL(SITE).host,
  iconUrl: new URL('icons/icon-512.png', SITE).toString(),
  includeSourceCode: false,
  isChromeOSOnly: false,
  isMetaQuest: false,
  launcherName: 'FreshCheck',
  maskableIconUrl: new URL('icons/icon-maskable-512.png', SITE).toString(),
  monochromeIconUrl: '',
  name: 'FreshCheck AI',
  navigationColor: '#0f3d27',
  navigationColorDark: '#0f3d27',
  navigationDividerColor: '#0f3d27',
  navigationDividerColorDark: '#0f3d27',
  orientation: 'portrait',
  packageId: 'io.github.bayern19feb.freshcheck',
  shortcuts: [],
  signing: {
    file: null,
    alias: 'freshcheck',
    fullName: 'FreshCheck AI Admin',
    organization: 'FreshCheck AI',
    organizationalUnit: 'School Science Exhibition',
    countryCode: 'IN',
    keyPassword: '', // generated by the service
    storePassword: '', // generated by the service
  },
  signingMode: 'new',
  splashScreenFadeOutDuration: 300,
  startUrl: new URL(SITE).pathname,
  themeColor: '#0f3d27',
  themeColorDark: '#0f3d27',
  webManifestUrl: new URL('manifest.webmanifest', SITE).toString(),
  pwaUrl: SITE,
  fullScopeUrl: SITE,
  minSdkVersion: 24,
};

const headers = { 'content-type': 'application/json', 'platform-identifier': 'FreshCheckAI-script', 'platform-identifier-version': '1.0.0', 'correlation-id': crypto.randomUUID() };

console.log('Requesting Android package for', SITE);
const enq = await fetch(`${SERVICE}/enqueuePackageJob`, { method: 'POST', headers, body: JSON.stringify(options) });
if (!enq.ok) {
  console.error('Enqueue failed:', enq.status, await enq.text());
  process.exit(1);
}
const receipt = await enq.json();
const auth = { Authorization: `Bearer ${receipt.accessToken}` };
console.log('Job queued:', receipt.id);

let job;
for (let i = 0; i < 120; i++) {
  await new Promise((r) => setTimeout(r, 5000));
  const res = await fetch(`${SERVICE}/getPackageJob?id=${encodeURIComponent(receipt.id)}`, { headers: auth, cache: 'no-store' });
  if (!res.ok) { console.log('status check failed', res.status); continue; }
  job = await res.json();
  console.log(`  ${new Date().toLocaleTimeString()} status: ${job.status}`);
  if (/^(completed|failed)$/i.test(job.status)) break;
}
if (!job || !/completed/i.test(job.status)) {
  console.error('Package job did not complete:', JSON.stringify(job)?.slice(0, 1500));
  process.exit(1);
}

const zip = await fetch(`${SERVICE}/downloadPackageZip?id=${encodeURIComponent(receipt.id)}`, { headers: auth });
if (!zip.ok) { console.error('Download failed', zip.status); process.exit(1); }
mkdirSync(OUT, { recursive: true });
writeFileSync(`${OUT}/FreshCheck-AI-android.zip`, Buffer.from(await zip.arrayBuffer()));
console.log(`Saved ${OUT}/FreshCheck-AI-android.zip`);
