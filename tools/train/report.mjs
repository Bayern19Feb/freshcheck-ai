// Chooses the confidence threshold on the VALIDATION photos, then measures the
// final results on the TEST photos, using the same code as the app's
// "Test the model" screen (public/js/evaluation.js).
// Writes docs/MODEL_EVALUATION.md and updates public/config/model-card.json.
// Run: node tools/train/report.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { evaluate, thresholdSweep } from '../../public/js/evaluation.js';
import { parseLabel, FRUITS, getFruit } from '../../public/js/fruits.js';

const PASS = { minPerClass: 20, minPrecision: 0.8, maxDangerous: 0 };
const STEPS = [0.5, 0.55, 0.6, 0.65, 0.7, 0.75, 0.8, 0.85, 0.9, 0.95];

const run = JSON.parse(readFileSync('data/heldout-scores.json', 'utf8'));
const card = JSON.parse(readFileSync('public/config/model-card.json', 'utf8'));
const minMargin = card.minMargin ?? 0.15;

const toItem = (s) => {
  const p = parseLabel(s.class);
  return p.kind === 'reject'
    ? { trueFruitId: null, trueConditionId: 'not-fruit', scores: s.scores }
    : { trueFruitId: p.fruitId, trueConditionId: p.conditionId, scores: s.scores };
};
const val = run.scored.filter((s) => s.split === 'validation').map(toItem);
const test = run.scored.filter((s) => s.split === 'test').map(toItem);

// ---- choose threshold on validation: no spoiled->fresh errors, then best accuracy, then lowest threshold
const sweep = thresholdSweep(val, { minMargin, steps: STEPS });
const minDanger = Math.min(...sweep.map((r) => r.dangerous));
const chosen = sweep
  .filter((r) => r.dangerous === minDanger)
  .sort((a, b) => b.accuracy - a.accuracy || a.threshold - b.threshold)[0];
const thresholds = { default: chosen.threshold, perFruit: {} };

// ---- final test
const ev = evaluate(test, { thresholds, minMargin });
const testSweep = thresholdSweep(test, { minMargin, steps: STEPS });
const pct = (x) => (x === null || x === undefined ? '—' : `${(x * 100).toFixed(1)}%`);

const testPerClass = {};
for (const it of test) {
  const k = it.trueConditionId === 'not-fruit' ? 'Other' : `${it.trueFruitId}:${it.trueConditionId}`;
  testPerClass[k] = (testPerClass[k] || 0) + 1;
}

const fruitRows = [];
const today = new Date().toISOString().slice(0, 10);
for (const f of FRUITS) {
  const b = ev.perFruit[f.id];
  if (!b) { fruitRows.push({ f, b: null, passed: false }); continue; }
  const perClassOk = ['fresh', 'spoiled'].every((c) => (testPerClass[`${f.id}:${c}`] || 0) >= PASS.minPerClass);
  const passed = perClassOk && b.precisionCovered !== null && b.precisionCovered >= PASS.minPrecision && b.dangerous <= PASS.maxDangerous;
  fruitRows.push({ f, b, passed });
  card.fruits[f.id] = {
    evaluation: passed ? 'passed' : 'failed',
    testImages: b.n,
    accuracy: Number(b.precisionCovered.toFixed(3)),
    notes: `${today}: dataset test photos only (not phone photos). Correct when answered ${pct(b.precisionCovered)}, answered ${pct(b.coverage)}, spoiled shown as fresh ${b.dangerous}.`,
  };
}

// ---- confusion matrix (rows = real, cols = app answer)
const keyName = (k) => (k === 'uncertain' ? 'Uncertain' : k === 'not-fruit' ? 'Other' : `${getFruit(k.split(':')[0]).name} ${k.split(':')[1] === 'fresh' ? 'F' : 'S'}`);
const rowsK = Object.keys(ev.matrix).sort();
const colsK = [...new Set(rowsK.filter((k) => k !== 'not-fruit').concat('uncertain'))];
for (const r of rowsK) for (const c of Object.keys(ev.matrix[r])) if (!colsK.includes(c)) colsK.push(c);

const counts = {};
for (const s of run.scored.concat()) counts[s.split] = (counts[s.split] || 0) + 1;
const last = run.history[run.history.length - 1];

const md = `# Model Evaluation — starter model (auto-generated)

Generated by \`node tools/train/report.mjs\` on ${today}. **Do not edit by hand — re-run the script.**

## Model
| Item | Value |
|---|---|
| Model name | ${run.metadata.modelName} |
| Export time (metadata timeStamp) | ${run.metadata.timeStamp} |
| Method | Teachable Machine library 0.8.5 (MobileNet v2, alpha 0.35, transfer learning) run in headless Chrome |
| Training settings | ${run.params.epochs} epochs, batch ${run.params.batchSize}, learning rate ${run.params.learningRate}, ${run.params.denseUnits} dense units, mirrored copies added: ${run.flipAugment ? 'yes' : 'no'}, seed \`${run.seed}\` |
| Classes (${run.labels.length}) | ${run.labels.map((l) => `\`${l}\``).join(', ')} |
| Photos | train ${counts.train ?? '—'} (listed in data/manifest.csv; not scored here), validation ${counts.validation}, test ${counts.test} |
| Last epoch (Teachable Machine's internal 15% split of training photos) | accuracy ${pct(last.acc)}, internal val accuracy ${pct(last.val_acc)} |
| Training time | ${Math.round(run.totalMs / 1000)} s on this PC (backend: ${run.backend}) |

## 1. Threshold chosen on the validation photos (${val.length} photos)
Rule: fewest "spoiled shown as fresh" errors, then highest overall accuracy, then the lower threshold. Minimum gap between top two classes: ${pct(minMargin)}.

| Threshold | Correct (all) | Answered | Correct when answered | Spoiled → fresh |
|---|---|---|---|---|
${sweep.map((r) => `| ${r.threshold === chosen.threshold ? `**${pct(r.threshold)}** ✔` : pct(r.threshold)} | ${pct(r.accuracy)} | ${pct(r.coverage)} | ${pct(r.precisionCovered)} | ${r.dangerous} |`).join('\n')}

**Chosen threshold: ${pct(chosen.threshold)}**

## 2. Final test (${test.length} photos never used for training or threshold choice)

| | Value |
|---|---|
| Correct (uncertain counts as not correct) | ${ev.total.correct}/${ev.total.n} = ${pct(ev.total.accuracy)} |
| Answered (not uncertain) | ${pct(ev.total.coverage)} |
| Correct when answered | ${pct(ev.total.precisionCovered)} |
| Spoiled shown as fresh | ${ev.total.dangerous} |

### Per fruit
Pass rule (project's own): ≥ ${PASS.minPerClass} test photos per class, correct when answered ≥ ${PASS.minPrecision * 100}%, spoiled shown as fresh = ${PASS.maxDangerous}.

| Fruit | Test photos | Correct (all) | Answered | Correct when answered | Fruit identified | Spoiled → fresh | Result |
|---|---|---|---|---|---|---|---|
${fruitRows.map(({ f, b, passed }) => (b ? `| ${f.name} | ${b.n} | ${pct(b.accuracy)} | ${pct(b.coverage)} | ${pct(b.precisionCovered)} | ${pct(b.fruitIdentified / b.n)} | ${b.dangerous} | ${passed ? '✅ passed' : '❌ not passed'} |` : `| ${f.name} | 0 | — | — | — | — | — | not in model |`)).join('\n')}
| Other (jujube, pomegranate) | ${ev.perFruit['not-fruit']?.n ?? 0} | ${pct(ev.perFruit['not-fruit']?.accuracy)} rejected as "not supported" | | | | | |

### Confusion matrix (test photos)
Rows = real label, columns = app answer. F = fresh, S = spoiled.

| Real ↓ / App → | ${colsK.map(keyName).join(' | ')} |
|---|${colsK.map(() => '---').join('|')}|
${rowsK.map((r) => `| **${keyName(r)}** | ${colsK.map((c) => ev.matrix[r][c] || 0).join(' | ')} |`).join('\n')}

### Test results at other thresholds (for information only — the threshold was fixed on validation photos)
| Threshold | Correct (all) | Answered | Correct when answered | Spoiled → fresh |
|---|---|---|---|---|
${testSweep.map((r) => `| ${pct(r.threshold)} | ${pct(r.accuracy)} | ${pct(r.coverage)} | ${pct(r.precisionCovered)} | ${r.dangerous} |`).join('\n')}

## 3. Important limitations of these numbers
- Test photos come from **the same public datasets** as the training photos (same cameras, backgrounds, lighting and often the same batches of fruit). Near-identical photos were kept on one side of the split, but results on **your own phone photos will very likely be lower**. Test with real fruit before claiming accuracy at the exhibition.
- The datasets label only **fresh** and **rotten**, so this model has **no "Overripe" class**.
- The "Other" class contains only jujube and pomegranate photos. It does not cover everyday non-fruit objects.
- Mango photos come from FruitVision (CC BY-NC-ND 4.0, non-commercial).
`;

writeFileSync('docs/MODEL_EVALUATION.md', md);

card.modelName = run.metadata.modelName;
card.modelVersion = 'starter-v1';
card.exportDate = run.metadata.timeStamp;
card.source = 'Starter model trained by the project with the Teachable Machine library (same method as the Teachable Machine website), from openly licensed public datasets. See docs/MODEL_EVALUATION.md.';
card.trainingData = `Public datasets: Project-AgML fresh_rotten_fruit_classification / Sultana et al. 2022 (CC BY 4.0) for apple, banana, orange, grapes, strawberry, guava and the "Other" class (jujube, pomegranate); Papaya Freshness Classification Dataset, Mendeley 7mgj5bvp5h (CC BY 4.0); FruitVision, Mendeley xkbjx8959c (CC BY-NC-ND 4.0) for mango. ${counts.train ?? 'n/a'} training photos (+ mirrored copies), ${val.length} validation, ${test.length} test. No overripe class.`;
card.testProcedure = `Threshold chosen on ${val.length} validation photos; final results measured on ${test.length} separate test photos from the same datasets (near-duplicates kept on one side of the split). Not yet tested on phone photos of real fruit.`;
card.lastVerified = today;
card.thresholds = thresholds;
card.thresholdNote = `Chosen on ${today} from ${val.length} validation photos (rule: fewest spoiled-shown-as-fresh errors, then best accuracy). Dataset photos only — re-check with your own phone photos.`;
card.knownLimitations = [
  'The model looks only at the outside of the fruit in one photo. It cannot see inside the fruit, detect bacteria or toxins, or decide whether food is safe to eat.',
  'It is a whole-image classifier: it does not point to particular spots, mould patches or defects.',
  'Trained and tested only on public dataset photos. Accuracy on your own phone photos, lighting and backgrounds is likely lower and has not been measured yet.',
  'No "overripe" class: the datasets only label fresh and rotten fruit, so ripe fruit with natural spots may be called spoiled.',
  'The "Other" class only contains jujube and pomegranate. Photos of everyday objects (not fruit) can still get a confident fruit label.',
];
writeFileSync('public/config/model-card.json', `${JSON.stringify(card, null, 2)}\n`);

console.log(`Threshold ${pct(chosen.threshold)} (validation). Test: correct ${pct(ev.total.accuracy)}, answered ${pct(ev.total.coverage)}, correct when answered ${pct(ev.total.precisionCovered)}, spoiled->fresh ${ev.total.dangerous}`);
for (const { f, b, passed } of fruitRows) console.log(`  ${f.name.padEnd(11)} ${b ? `${pct(b.precisionCovered).padStart(6)} answered-correct, ${pct(b.coverage).padStart(6)} answered, danger ${b.dangerous} -> ${passed ? 'PASSED' : 'not passed'}` : 'not in model'}`);
